#!/usr/bin/env node
/*
 * @catalog what    Seeds mission_gates/{boxId} to production Firestore. THIS ARMS THE #306
 * @catalog what    reveal gate: 12 missions begin requiring a real evidence ledger.
 * @catalog run     node functions/seed-mission-gates.js            (dry run, default)
 * @catalog run     node functions/seed-mission-gates.js --arm      (writes to production)
 * @catalog run     node functions/seed-mission-gates.js --disarm   (removes the gate)
 * @catalog status  TOOL
 *
 * ⚠ THIS IS THE DANGEROUS STEP OF #306 AND THE ONLY ONE THAT CHANGES WHAT STUDENTS SEE.
 *
 * Everything else in #306 is inert without this document: assertGateSatisfied returns null
 * when it is absent, so validateFlag behaves exactly as it always has. Writing it makes 12
 * missions require findings the server itself recorded. If anything in the browser ->
 * recordMissionFinding -> Firestore chain is wrong, those missions become UNCOMPLETABLE for
 * every student, and it will look like the box is simply broken.
 *
 * So: dry run by default, --arm is explicit, and --disarm exists and is tested BEFORE arming
 * rather than discovered during an incident. Rollback is deleting one document, after which
 * the code fails open again by design.
 *
 * The spec is GENERATED by gen-mission-gates.js from the mission data. Do not hand-edit the
 * JSON: it would drift from the missions on the first content change, and a gate that drifts
 * open is worse than no gate while a gate that drifts closed rejects correct answers.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const admin = require('firebase-admin');

const SPEC = path.join(__dirname, 'mission-gates.generated.json');
const ARM = process.argv.includes('--arm');
const DISARM = process.argv.includes('--disarm');

if (!fs.existsSync(SPEC) && !DISARM) {
    console.error('No generated spec. Run: node functions/gen-mission-gates.js --write');
    process.exit(1);
}

try { admin.initializeApp({ projectId: 'hexworth-prime' }); } catch (e) { /* already initialised */ }
const db = admin.firestore();

(async () => {
    if (DISARM) {
        const ref = db.doc('mission_gates/le-01-cold-horizon');
        const before = await ref.get();
        if (!before.exists) { console.log('Already disarmed: no gate document.'); process.exit(0); }
        /* We do not destroy. The document is generated and reproducible, but capture it
           anyway: an incident is the worst moment to discover a file was not kept. */
        const stamp = before.data();
        const backup = path.join(__dirname, 'mission-gates.disarmed-backup.json');
        fs.writeFileSync(backup, JSON.stringify(stamp, null, 2));
        console.log(`Archived the live document to ${backup}`);
        await ref.delete();
        console.log('DISARMED. mission_gates/le-01-cold-horizon deleted.');
        console.log('validateFlag fails open again; every mission behaves as it did before arming.');
        process.exit(0);
    }

    const spec = JSON.parse(fs.readFileSync(SPEC, 'utf8'));
    const gates = spec.gates || {};
    const ids = Object.keys(gates);

    console.log(`\nBox      : ${spec.boxId}`);
    console.log(`Gates    : ${ids.length}`);
    ids.forEach(k => {
        const g = gates[k];
        console.log(`  ${k.padEnd(22)} ${String(g.necessaries.length)} necessaries, `
                  + `${g.corroboratorsRequired} ${g.corroboratorFamily} corroborator, `
                  + `${Object.keys(g.sources).length} sources`);
    });

    const ref = db.doc(`mission_gates/${spec.boxId}`);
    const existing = await ref.get();
    console.log(`\nCurrently armed: ${existing.exists}`);

    if (!ARM) {
        console.log('\nDRY RUN. Nothing written. Pass --arm to write this to production.');
        console.log('Missions NOT gated (no derivable spec, they behave as today):');
        console.log('  m1 (no held payload), m12, m13');
        process.exit(0);
    }

    await ref.set({
        boxId: spec.boxId,
        generatedFrom: spec.generatedFrom,
        armedAt: admin.firestore.FieldValue.serverTimestamp(),
        gates
    });
    console.log(`\nARMED. Wrote mission_gates/${spec.boxId} with ${ids.length} gates.`);
    console.log('Verify one mission by hand NOW. Rollback: node functions/seed-mission-gates.js --disarm');
    process.exit(0);
})().catch(e => { console.error('SEED ERROR: ' + e.message); process.exit(1); });
