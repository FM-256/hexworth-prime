#!/usr/bin/env node
/**
 * gen-house-tracks.js
 *
 * @catalog what    Generates _app/components/HouseTracks.js: the house -> course-track map that
 * @catalog what    puts real content links on the 13 careers.html pages. Derived from the
 * @catalog what    generated course-trees catalog, never hand-maintained.
 * @catalog run     node _tools/career/gen-house-tracks.js [--check]
 * @catalog status  GATE
 *
 * WHY THIS IS GENERATED
 * ---------------------
 * The platform already had three disconnected career systems, each with its own hand-written
 * idea of what content exists (career-paths.html's HOUSES array, CareerPaths.js, and
 * CareerExplorerEngine.js). Adding a fourth hand-maintained list is how the fourth one goes
 * stale too. `_app/data/course-trees/*.json` is generated by the crawler and already carries,
 * per track, the canonical entry `hub` and a verified `broken` count. That is the source of
 * truth; this script projects it.
 *
 * `--check` re-derives and diffs against the committed output, exiting non-zero on drift. That
 * makes the artifact falsifiable: a track that moves or rots cannot silently keep a nav link.
 *
 * SELECTION RULES (deliberate, and each one is a judgment you can argue with)
 *   - A track is `houses--<house>--<track>`, `dark-arts--vault--<track>`, or `signal--<track>`.
 *   - BLOCKED slugs are containers, not courses (applets, reviews, exams, labs, games...).
 *   - MIN_NODES filters stubs. A 3-node tree is not a track you send a student to.
 *   - MAX_BROKEN_RATIO is a ratio, not a zero. 2 broken links out of 488 is a healthy course;
 *     11 out of 212 is not. An absolute `broken > 0` test drops Code and Script for rounding.
 *   - Near-duplicate trees within a house (same content crawled under two slugs) collapse to
 *     the larger one.
 *   - NO CAP, and output is sorted alphabetically. An earlier version kept the six biggest
 *     trees, which silently dropped CompTIA Security+ from the Shield careers page: crawl
 *     breadth is not importance, and Security+ is that house's anchor cert but only its 7th
 *     largest tree. Ranking by size was an arbitrary judgment that quietly deleted the most
 *     important link on the page, and it took LOOKING at a screenshot to catch. Alphabetical
 *     implies no ranking and cannot drop anything.
 *
 * A house with no qualifying track gets NO entry, and the component renders nothing for it.
 * That is intentional: House of the Key has 52 HTML files but a 3-node link tree, so it has a
 * content-wiring problem that a fabricated nav link would hide rather than fix.
 */

const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '../..');
const TREES = path.join(REPO, '_app/data/course-trees');
const OUT = path.join(REPO, '_app/components/HouseTracks.js');

const BLOCK = new Set(['applets', 'reviews', 'exams', 'modules', 'hubs', 'simulators', 'textbook',
    'troubleshooting', 'incubator', 'games', 'gates', 'dojo', 'labs', 'tools', 'challenges',
    'certs', 'instructor']);
const MIN_NODES = 40;
const MAX_BROKEN_RATIO = 0.02;

/** Strip the house/branding suffix a crawled <title> carries, and decode entities. */
function cleanTitle(raw) {
    let t = String(raw || '');
    t = t.replace(/&mdash;/g, '|').replace(/&amp;/g, '&').replace(/&[a-z]+;/g, ' ');
    // Cut at the first branding separator. Order matters: check two-char forms first.
    const cut = t.search(/\s(?:\/\/|--|—|–|\|)\s/);
    if (cut !== -1) t = t.slice(0, cut);
    // Trailing "- House of the X", "- The Vault", "- Shield", "- ... Hub"
    t = t.replace(/\s*-\s*(House of[^-]*|The Vault|Shield|[A-Za-z0-9 &/]*Hub)\s*$/i, '');
    return t.replace(/\s+/g, ' ').trim().replace(/[\s\-|]+$/, '');
}

/** Collapse "The Algorithm Chamber" and "Algorithm Chamber - CS Fundamentals Hub". */
function dedupeKey(title) {
    return title.toLowerCase().replace(/^the\s+/, '').replace(/[^a-z0-9]/g, '');
}

function collect() {
    const skipped = [];
    const byHouse = {};

    for (const file of fs.readdirSync(TREES).filter(f => f.endsWith('.json')).sort()) {
        const key = file.slice(0, -5);
        const p = key.split('--');
        let house, slug;
        if (p[0] === 'houses' && p.length === 3) { house = p[1]; slug = p[2]; }
        else if (p[0] === 'dark-arts' && p.length === 3) { house = 'dark-arts'; slug = p[2]; }
        else if (p[0] === 'signal' && p.length === 2) { house = 'signal'; slug = p[1]; }
        else continue;
        if (BLOCK.has(slug)) continue;

        let d;
        try { d = JSON.parse(fs.readFileSync(path.join(TREES, file), 'utf8')); }
        catch (e) { skipped.push(`${key}: unparseable (${e.message})`); continue; }

        const s = d.stats || {};
        const nodes = s.totalNodes || 0;
        const broken = s.broken || 0;
        if (!d.hub) { skipped.push(`${key}: no hub path`); continue; }
        if (nodes < MIN_NODES) { skipped.push(`${key}: ${nodes} nodes < ${MIN_NODES}`); continue; }
        if (nodes && broken / nodes > MAX_BROKEN_RATIO) {
            skipped.push(`${key}: broken ${broken}/${nodes} = ${(broken / nodes * 100).toFixed(1)}%`);
            continue;
        }

        const title = cleanTitle(d.title) || slug;
        const url = '/' + d.hub.replace(/index\.html$/, '');
        (byHouse[house] = byHouse[house] || []).push({ slug, title, url, nodes });
    }

    // Dedupe near-identical trees. The size sort here is ONLY so a duplicate pair resolves to
    // the larger tree; it does not order the output. Output is alphabetical and uncapped, so a
    // house's anchor course cannot be silently dropped for being a smaller crawl.
    for (const house of Object.keys(byHouse)) {
        const seen = new Map();
        for (const t of byHouse[house].sort((a, b) => b.nodes - a.nodes)) {
            const k = dedupeKey(t.title);
            if (!seen.has(k)) seen.set(k, t);
            else skipped.push(`${house}/${t.slug}: duplicate of ${seen.get(k).slug}`);
        }
        byHouse[house] = [...seen.values()].sort((a, b) => a.title.localeCompare(b.title));
    }
    return { byHouse, skipped };
}

/**
 * The emitted component is self-mounting: it derives the house from the URL rather than taking
 * per-page configuration, so wiring a careers page is one <script> tag and nothing else.
 */
function render(byHouse) {
    const houses = Object.keys(byHouse).sort();
    const data = houses.map(h => {
        const items = byHouse[h].map(t =>
            `        { title: ${JSON.stringify(t.title)}, url: ${JSON.stringify(t.url)} }`).join(',\n');
        return `    ${JSON.stringify(h)}: [\n${items}\n    ]`;
    }).join(',\n');

    return `/**
 * HouseTracks.js: GENERATED FILE, DO NOT EDIT BY HAND.
 *
 * Regenerate:  node _tools/career/gen-house-tracks.js
 * Verify:      node _tools/career/gen-house-tracks.js --check
 *
 * Puts real course links on the careers pages. Before this existed, every careers.html
 * described a career and linked to no content that teaches it. houses/dark-arts/careers.html
 * advertised "Bug Bounty Hunter" in its schema.org tag while linking to zero of the 70 files
 * under /dark-arts/vault/bug-hunting/.
 *
 * Source of truth is _app/data/course-trees/*.json (generated by the crawler, carries a
 * canonical hub path and a verified broken-link count per track). Selection rules and the
 * reasoning behind each are in the generator.
 *
 * Self-mounting: include one script tag before <hex-ai-button> and nothing else. The house is
 * derived from the URL, so there is no per-page data to keep in sync.
 */
(function () {
    'use strict';

    var TRACKS = {
${data}
    };

    /** /houses/<house>/careers.html or /signal/careers.html -> house id. */
    function houseFromPath(pathname) {
        var m = /^\\/houses\\/([a-z0-9-]+)\\//.exec(pathname);
        if (m) return m[1];
        if (/^\\/signal\\//.test(pathname)) return 'signal';
        return null;
    }

    function build(tracks) {
        var section = document.createElement('section');
        section.className = 'house-tracks';
        section.id = 'house-tracks';

        var h2 = document.createElement('h2');
        h2.className = 'house-tracks-title';
        h2.textContent = 'Learn this at Hexworth';
        section.appendChild(h2);

        var p = document.createElement('p');
        p.className = 'house-tracks-sub';
        p.textContent = 'Courses on this platform that build toward these roles.';
        section.appendChild(p);

        var list = document.createElement('ul');
        list.className = 'house-tracks-list';
        tracks.forEach(function (t) {
            var li = document.createElement('li');
            var a = document.createElement('a');
            a.href = t.url;
            a.className = 'house-tracks-link';
            a.textContent = t.title;
            li.appendChild(a);
            list.appendChild(li);
        });
        section.appendChild(list);
        return section;
    }

    var CSS = [
        '.house-tracks{max-width:1100px;margin:48px auto;padding:28px 24px;',
        'border:1px solid rgba(255,255,255,0.10);border-radius:12px;',
        'background:rgba(255,255,255,0.03);}',
        '.house-tracks-title{font-size:20px;font-weight:700;margin:0 0 6px;}',
        '.house-tracks-sub{font-size:13px;opacity:0.72;margin:0 0 18px;}',
        '.house-tracks-list{list-style:none;margin:0;padding:0;display:grid;gap:10px;',
        'grid-template-columns:repeat(auto-fill,minmax(240px,1fr));}',
        '.house-tracks-link{display:block;padding:12px 14px;border-radius:8px;',
        'border:1px solid rgba(255,255,255,0.10);text-decoration:none;font-size:14px;',
        'color:inherit;transition:border-color .2s,background .2s;}',
        '.house-tracks-link:hover,.house-tracks-link:focus-visible{',
        'border-color:currentColor;background:rgba(255,255,255,0.06);}',
        '.house-tracks-link:focus-visible{outline:2px solid currentColor;outline-offset:2px;}',
        '@media (max-width:680px){.house-tracks{margin:32px 16px;padding:20px 16px;}}'
    ].join('');

    function mount() {
        if (document.getElementById('house-tracks')) return;
        var house = houseFromPath(window.location.pathname);
        var tracks = house && TRACKS[house];
        if (!tracks || !tracks.length) return;   // no invented links for a house with no tracks

        var style = document.createElement('style');
        style.textContent = CSS;
        document.head.appendChild(style);

        var section = build(tracks);
        // Every careers page ends with <hex-ai-button>; sit above it, else append to body.
        var anchor = document.querySelector('hex-ai-button');
        if (anchor && anchor.parentNode) anchor.parentNode.insertBefore(section, anchor);
        else document.body.appendChild(section);
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', mount);
    } else {
        mount();
    }
})();
`;
}

function main() {
    const check = process.argv.includes('--check');
    const { byHouse, skipped } = collect();
    const out = render(byHouse);

    const houses = Object.keys(byHouse).sort();
    const total = houses.reduce((n, h) => n + byHouse[h].length, 0);

    if (check) {
        const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
        if (current !== out) {
            console.error('DRIFT: _app/components/HouseTracks.js does not match the course-trees catalog.');
            console.error('Run: node _tools/career/gen-house-tracks.js');
            process.exit(1);
        }
        console.log(`OK: HouseTracks.js matches the catalog (${houses.length} houses, ${total} tracks).`);
        return;
    }

    fs.writeFileSync(OUT, out);
    console.log(`Wrote ${path.relative(REPO, OUT)}: ${houses.length} houses, ${total} tracks.`);
    for (const h of houses) {
        console.log(`  ${h.padEnd(11)} ${byHouse[h].map(t => t.title).join(' | ')}`);
    }
    console.log(`\nSkipped ${skipped.length} trees (each with its reason):`);
    for (const s of skipped.slice(0, 12)) console.log(`  ${s}`);
    if (skipped.length > 12) console.log(`  ...and ${skipped.length - 12} more`);
}

main();
