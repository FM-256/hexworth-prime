#!/usr/bin/env node
'use strict';
/*
 * @catalog what    Refreshes _tools/content/legacy-completion-ids.json from LIVE progress data so the
 * @catalog what    completion registry cannot reject work a student has already earned. --check fails
 * @catalog what    if live data holds an id the committed floor does not.
 * @catalog run     node _tools/content/refresh-legacy-floor.js [--check]
 * @catalog status  TOOL
 *
 * WHY THIS EXISTS. `completion-registry.json` is the server-side allowlist of ids the platform may
 * award, and `_isKnownCompletion` (functions/index.js:416) is the check that uses it. Enforcement is
 * OFF — `_ENFORCE_COMPLETION_REGISTRY = false` — because turning it on rejected legitimate work and
 * broke 74 live AI-102 pages on 2026-09-07. The registry's declared sources (LearningPaths,
 * trackerKeys, literal call sites) cover barely half of what students actually hold, because many
 * completion ids are built at runtime from a template or a loop variable and are not statically
 * resolvable. The legacy FLOOR is what closes that gap: ground truth, taken from the data.
 *
 * THE FLOOR WAS A ONE-OFF AND WENT STALE, WHICH IS THE WHOLE PROBLEM. It was generated by hand on
 * 2026-09-07 and had no regenerator, so it froze. Measured 2026-10-07 against production: students
 * hold 544 distinct completion ids on the legacy class surface alone and 188 of them are absent from
 * the registry — overwhelmingly WSA module ids earned after the snapshot was taken. Enforcement
 * today would reject every one. That is precisely the failure the registry generator's own header
 * warns about: "If you ship new content without regenerating, every student who completes it is
 * rejected — the same data loss this file exists to prevent." A floor with no regenerator guarantees
 * it.
 *
 * ── THE ONE INVARIANT: THE FLOOR ONLY EVER GROWS ─────────────────────────────────────────────────
 * Every id in this file is a claim that a real student earned that work. Removing one re-arms the
 * rejection. So this tool UNIONS live ids into the committed set and never subtracts, and it refuses
 * to write at all when the live read looks degraded — zero ids found, or a surface that returns
 * nothing. A transient permission error or an empty query must not be allowed to silently shrink the
 * floor; that failure would look like a successful run and would cost students their progress. An
 * overwrite-from-scratch design would have exactly that failure mode, which is why this is a union.
 *
 * NOTHING IS EXCLUDED, and that is inherited doctrine rather than caution. One id was dropped as
 * "garbage" on 2026-09-07 and that was wrong: `forge-forge-core2-virtualization-lab` is declared at
 * ContentCatalog.js:524 and completed by a real page. A student earned it. The mistake survived a
 * review and a deploy because nobody opened the catalogue. If you are about to exclude an id, don't.
 *
 * SURFACES READ, all read-only, CONTENT IDS ONLY — never a uid, never a display name, never a score:
 *   users/{uid}                                         modulesCompleted[], labsCompleted[], quizzes{} keys
 *   classes/{c}/progress/{uid}            (4 segments)  completions{} keys          <- the surface the
 *                                                        2026-09-07 snapshot missed entirely
 *   tenants/{t}/classes/{c}/progress/{uid} (6 segments)  modulesCompleted[], labsCompleted[],
 *                                                        quizScores{} keys
 * `achievements[]` is deliberately NOT read: it is a separate id space and a separate defect
 * (taskboard 304, syncProgress unions client-supplied achievements with no catalog check). Mixing it
 * in would widen the completion allowlist with ids that were never completions.
 *
 * AFTER RUNNING THIS, REGENERATE THE REGISTRY: node _tools/content/gen-completion-registry.js
 * The floor is an input to that build; refreshing one without the other changes nothing.
 *
 * EXIT: 0 written / already in sync. 1 stale (--check only). 2 could not run — including any
 * degraded read, because a floor written from partial data is worse than a stale one.
 */
const fs = require('fs');
const path = require('path');
/* firebase-admin lives ONLY in functions/node_modules — there is no top-level install. A bare
 * require('firebase-admin') therefore resolves only when the cwd happens to sit under functions/,
 * which is how the first run of this tool succeeded and why running it from the repo root (the
 * normal invocation, and the one a deploy gate would use) crashed. The crash exits 2, so it never
 * silently passed a stale floor — but the tool was unusable from the place it is actually run.
 * Resolve the way the rest of the tree does: an explicit path, with the bare form tried first so a
 * future top-level install keeps working. */
function loadAdmin() {
    try { return require('firebase-admin'); } catch (e) {
        if (e && e.code !== 'MODULE_NOT_FOUND') throw e;
    }
    const p = path.join(__dirname, '..', '..', 'functions', 'node_modules', 'firebase-admin');
    try { return require(p); } catch (e) {
        if (e && e.code !== 'MODULE_NOT_FOUND') throw e;
        console.error('  firebase-admin not resolvable — tried the bare module and ' + p);
        console.error('  Run `npm install` in functions/. Refusing to proceed: a floor cannot be');
        console.error('  refreshed without reading live data, and a stale floor must not look fresh.');
        process.exit(2);
    }
}
const admin = loadAdmin();

const FLOOR = path.join(__dirname, 'legacy-completion-ids.json');
const CHECK = process.argv.includes('--check');

function idsFromUserDoc(d) {
    const out = [];
    for (const f of ['modulesCompleted', 'labsCompleted']) {
        const v = d[f];
        if (Array.isArray(v)) for (const x of v) if (typeof x === 'string' && x) out.push(x);
    }
    if (d.quizzes && typeof d.quizzes === 'object') out.push(...Object.keys(d.quizzes));
    return out;
}

function idsFromProgressDoc(d) {
    const out = [];
    // legacy shape
    if (d.completions && typeof d.completions === 'object') out.push(...Object.keys(d.completions));
    // tenant shape
    for (const f of ['modulesCompleted', 'labsCompleted']) {
        const v = d[f];
        if (Array.isArray(v)) for (const x of v) if (typeof x === 'string' && x) out.push(x);
    }
    if (d.quizScores && typeof d.quizScores === 'object') out.push(...Object.keys(d.quizScores));
    return out;
}

/* STRUCTURAL REJECTS, AND WHY EXCLUDING THESE IS NOT THE 2026-09-07 MISTAKE.
 * The doctrine inherited from legacy-completion-ids.json is that nothing is excluded, because one id
 * was dropped as "garbage" on 2026-09-07 and that was wrong — a student had earned it. That rule
 * protects ids a student EARNED. It does not require blessing ids that no completion could produce.
 *
 * Measured on production 2026-10-07, three keys in the legacy `completions` maps cannot be content
 * ids at all: `undefined`, `[object Object]` and `any_id`. The first two are what
 * AssignmentManager.submitProgress writes when it is handed a missing or non-string contentId — the
 * same class of client-side defect as the literal dotted keys cleaned on 2026-10-01. The third is a
 * test placeholder that reached production. Putting any of them in the allowlist would make the
 * allowlist bless malformed writes, which is the opposite of its purpose.
 *
 * So they are rejected AND RECORDED in the floor's `excluded` field with this reasoning, never
 * dropped silently. Silence is what let the 2026-09-07 error survive a review and a deploy. If a
 * later reader believes one of these is real, the record is there to argue with. */
/* ── NANCY BLOCKED THE FIRST VERSION OF THIS PREDICATE, AND SHE WAS RIGHT ────────────────────────
 * It rejected any id containing a dot, reasoned as "a dotted field NAME artifact." That is
 * FALSIFIED by real, declared, currently-reachable content:
 *     dark-arts-redteam.barricade   _app/dark-arts/vault/modules/redteam.barricade.html:15
 *     shield-eh-exam-1-a.exam       _app/houses/shield/exams/shield-eh-exam-1-a.exam.html:264
 * Both are written by ModuleProgress.complete(), which syncs to users/{uid} and tenant
 * classes/{c}/progress — the exact surfaces this tool reads — and both are ALREADY in
 * functions/completion-registry.json, extracted by gen-completion-registry.js's call-site parser,
 * which applies no dot filter. So the canonical builder considered them legitimate while this
 * predicate called them garbage.
 *
 * The consequence was worse than a cosmetic disagreement: a dark-arts or shield-exam completion
 * missing from the registry would have been filed as "malformed (expected, not a blocker)" instead
 * of the real coverage BLOCKER it is, in BOTH tools, because registry-coverage.js shares this
 * predicate. The dot rule was speculative hardening, it was wrong, and it would have hidden exactly
 * the class of failure this chain exists to catch. It only stayed invisible in the first run by
 * luck — no live completion for that low-enrollment family happened to be missing yet.
 *
 * THE RULE NOW: reject ONLY what is provably impossible as a content id. Over-rejecting costs a
 * student earned progress, which is unrecoverable harm; under-rejecting merely widens an allowlist.
 * Those costs are not symmetric, so the predicate is deliberately minimal.
 *
 * Note the explicit dot and slash tests are both GONE. SHAPE now permits dots, and it already
 * rejects slashes because `/` is not in its character class — a separate slash test added nothing
 * except a second place to get the same judgment wrong. (Nancy's proposed remedy was "keep the
 * SENTINELS plus SHAPE"; applied literally that still rejects both ids, because the old SHAPE
 * excluded dots too. Fixing the shape is the actual fix.) */
const SENTINELS = new Set(['undefined', 'null', 'NaN', 'any_id', '[object Object]', 'true', 'false']);
const SHAPE = /^[A-Za-z0-9][A-Za-z0-9_.-]*$/;
function rejectReason(id) {
    if (!id || typeof id !== 'string') return 'not a non-empty string';
    if (id.length > 200) return 'longer than 200 chars';
    if (SENTINELS.has(id)) return 'sentinel value from a client passing a missing/non-string contentId, or a test placeholder';
    if (!SHAPE.test(id)) return 'not identifier-shaped (letters, digits, hyphen, underscore, dot)';
    return null;
}
const BAD = (id) => rejectReason(id) !== null;

async function main() {
    if (!fs.existsSync(FLOOR)) {
        console.error('  legacy-completion-ids.json missing — refusing to create a floor from scratch.');
        console.error('  A floor built from one run of one query is not a floor. Restore the file first.');
        return 2;
    }
    const floor = JSON.parse(fs.readFileSync(FLOOR, 'utf8'));
    const existing = new Set(floor.ids || []);
    if (!existing.size) { console.error('  committed floor is EMPTY — refusing to proceed.'); return 2; }

    admin.initializeApp({ projectId: 'hexworth-prime' });
    const db = admin.firestore();

    const found = new Set();
    const rejects = new Map();   // id -> reason, recorded not discarded
    const per = { users: 0, legacyClass: 0, tenantClass: 0 };
    let userDocs = 0, progressDocs = 0;

    const us = await db.collection('users').get();
    userDocs = us.size;
    for (const d of us.docs) for (const id of idsFromUserDoc(d.data())) {
        const r = rejectReason(id);
        if (r) { rejects.set(String(id).slice(0, 60), r); continue; }
        found.add(id); per.users++;
    }

    const pg = await db.collectionGroup('progress').get();
    progressDocs = pg.size;
    for (const d of pg.docs) {
        const segs = d.ref.path.split('/').length;
        const bucket = segs === 4 ? 'legacyClass' : 'tenantClass';
        for (const id of idsFromProgressDoc(d.data())) {
            const r = rejectReason(id);
            if (r) { rejects.set(String(id).slice(0, 60), r); continue; }
            found.add(id); per[bucket]++;
        }
    }

    // DEGRADED-READ GUARD. Either surface returning nothing means the read, not the data, is wrong.
    if (userDocs === 0 || progressDocs === 0 || found.size === 0) {
        console.error(`  DEGRADED READ — refusing to write. users=${userDocs} progressDocs=${progressDocs} ids=${found.size}`);
        console.error('  A floor written from a partial read silently deletes earned progress. Fix access and re-run.');
        return 2;
    }

    const added = [...found].filter((id) => !existing.has(id)).sort();
    console.log(`  read ${userDocs} user docs + ${progressDocs} progress docs (read-only, content ids only)`);
    console.log(`  live ids: ${found.size}   committed floor: ${existing.size}   NEW: ${added.length}`);
    if (added.length) console.log(`  sample new: ${added.slice(0, 8).join(', ')}${added.length > 8 ? ' …' : ''}`);
    if (rejects.size) {
        console.log(`  REJECTED ${rejects.size} malformed id(s) — recorded in the floor's excluded field, not discarded silently:`);
        for (const [id, why] of rejects) console.log(`     ${JSON.stringify(id)} :: ${why}`);
    }

    if (!added.length) { console.log('  floor already covers every live id — in sync.'); return 0; }
    if (CHECK) {
        console.error(`  STALE: ${added.length} id(s) students hold are missing from the committed floor.`);
        console.error('  Run without --check, then regenerate the registry.');
        return 1;
    }

    const union = [...new Set([...existing, ...found])].sort();
    if (union.length < existing.size) { console.error('  union is SMALLER than the committed floor — impossible; aborting.'); return 2; }

    floor.excluded = {
        ids: [...rejects.keys()].sort(),
        reason: 'STRUCTURALLY IMPOSSIBLE AS CONTENT IDS, recorded rather than silently dropped. Each is what '
            + 'AssignmentManager.submitProgress writes when handed a missing or non-string contentId, or a test '
            + 'placeholder that reached production. This is NOT the 2026-09-07 mistake: that excluded an id a '
            + 'student had EARNED (forge-forge-core2-virtualization-lab, declared at ContentCatalog.js:524). '
            + 'Blessing these would make the allowlist endorse malformed writes. If you believe one is real, '
            + 'open the catalogue first — the 2026-09-07 error survived a review because nobody did.',
        recordedBy: '_tools/content/refresh-legacy-floor.js'
    };
    floor.ids = union;
    floor.count = union.length;
    /* LOCAL date, not UTC. `toISOString().slice(0,10)` stamped 2026-10-08 on a run made at 21:37 EDT
     * on 2026-10-07, so the floor disagreed with every other record written in the same session
     * (BUG tracker, commit message, SITREP). A durable artifact dated a day ahead of the work reads
     * as clock skew to whoever audits it next. */
    const _d = new Date();
    floor.generated = `${_d.getFullYear()}-${String(_d.getMonth() + 1).padStart(2, '0')}-${String(_d.getDate()).padStart(2, '0')}`;
    floor.derivedFrom = 'users/{uid} + collectionGroup(progress) across BOTH the legacy classes/{c}/progress '
        + 'and tenants/{t}/classes/{c}/progress surfaces, refreshed by _tools/content/refresh-legacy-floor.js';
    floor.why = (floor.why || '') + ` REFRESHED ${floor.generated}: +${added.length} ids students hold that the `
        + '2026-09-07 one-off snapshot predated. Union only, never subtracted.';
    fs.writeFileSync(FLOOR, JSON.stringify(floor, null, 2) + '\n');
    console.log(`  wrote floor: ${existing.size} -> ${union.length} ids (+${added.length})`);
    console.log('  NEXT: node _tools/content/gen-completion-registry.js');
    return 0;
}

/* The reject predicate is EXPORTED so registry-coverage.js can share it instead of keeping a second
 * copy. Two copies of a classifier drift, and the drift is silent: the copy that is wrong simply
 * stops matching, and a probe using it reports clean. One definition, two consumers. */
module.exports = { rejectReason, SENTINELS, SHAPE };

if (require.main === module) {
    main().then((c) => process.exit(c)).catch((e) => { console.error('  refresh-legacy-floor failed:', e && e.message); process.exit(2); });
}
