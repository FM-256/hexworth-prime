    /**
     * Normalize a Manager definition to unified schema
     */
    function normalizeManagerDef(def) {
        // Determine subcategory for games
        let subcategory = null;
        if (def.id.startsWith('game_')) {
            if (['game_packetrun','game_bitdash','game_shellsprint','game_threatrunner','game_cloudhop'].includes(def.id)) {
                subcategory = 'games_runner';
            } else if (['game_sudo','game_nmap','game_incident','game_gpg','game_grep','game_fsck','game_gitblame','game_awssts','game_tor','game_kill9'].includes(def.id)) {
                subcategory = 'games_text';
            } else {
                subcategory = 'games_arcade';
            }
        } else if (def.id.startsWith('cli_')) {
            subcategory = 'cli';
        } else if (def.id.startsWith('gate_') || def.id === 'dark-arts-master') {
            subcategory = 'dark_arts';
        }

        return {
            id: def.id,
            name: def.name,
            description: def.desc || def.description || '',
            icon: def.icon,
            category: CATEGORY_MAP[def.category] || def.category || 'general',
            subcategory: subcategory || (def.id.startsWith('cli_') ? 'cli' : null),
            points: def.points || 0,
            secret: def.category === 'secret',
            title: def.title || null,
            style: def.style || null,
            source: 'manager',
            autoGenerated: false
        };
    }

    /**
     * Normalize a System definition to unified schema
     */
    function normalizeSystemDef(def) {
        // Determine subcategory
        let subcategory = null;
        const origCategory = def.category;
        if (origCategory === 'games') {
            if (def.id.includes('_win') || def.id.includes('_by_the_book') || def.id.includes('_speed') || def.id.includes('_all') || def.id === 'game_master_survivor') {
                subcategory = 'games_survival';
            } else {
                subcategory = 'games_arcade';
            }
        } else if (['shield','web','forge','script','cloud','code','key','eye'].includes(origCategory)) {
            subcategory = origCategory;
        }

        return {
            id: def.id,
            name: def.name,
            description: def.description || def.desc || '',
            icon: def.icon,
            category: CATEGORY_MAP[origCategory] || origCategory || 'general',
            subcategory: subcategory,
            points: def.points || 0,
            secret: def.secret === true,
            title: null,  // System doesn't have titles
            style: null,  // System doesn't have styles
            source: 'system',
            seasonal: def.seasonal || null,
            limited: def.limited || false,
            autoGenerated: false
        };
    }

    /**
     * Merge overlapping definitions: System desc+points, Manager title+style
     */
    function mergeOverlap(managerDef, systemDef) {
        const merged = normalizeSystemDef(systemDef);
        const mNorm = normalizeManagerDef(managerDef);
        // Take title and style from Manager
        merged.title = mNorm.title;
        merged.style = mNorm.style;
        // Keep Manager's category mapping if more specific
        if (mNorm.category === 'secret' || mNorm.category === 'legendary') {
            merged.secret = mNorm.secret;
        }
        merged.source = 'both';
        return merged;
    }

    /**
     * Build the unified definitions map from both sources
     */
    function buildDefinitions() {
        const defs = new Map();

        // Pull from AchievementManager if available
        if (typeof AchievementManager !== 'undefined') {
            const managerDefs = AchievementManager.getAllAchievements();
            for (const def of managerDefs) {
                if (OVERLAP_IDS.has(def.id)) continue; // Handle overlaps separately
                defs.set(def.id, normalizeManagerDef(def));
            }
        }

        // Pull from AchievementSystem if available
        if (typeof AchievementSystem !== 'undefined') {
            const systemDefs = AchievementSystem.ACHIEVEMENTS;
            for (const [key, def] of Object.entries(systemDefs)) {
                if (OVERLAP_IDS.has(def.id)) continue; // Handle overlaps separately
                if (!defs.has(def.id)) {
                    defs.set(def.id, normalizeSystemDef(def));
                }
            }
        }

        // Handle overlaps
        for (const id of OVERLAP_IDS) {
            const managerAll = (typeof AchievementManager !== 'undefined') ? AchievementManager.getAllAchievements() : [];
            const mDef = managerAll.find(a => a.id === id);
            const sDef = (typeof AchievementSystem !== 'undefined') ? AchievementSystem.ACHIEVEMENTS[id] : null;
            if (mDef && sDef) {
                defs.set(id, mergeOverlap(mDef, sDef));
            } else if (mDef) {
                defs.set(id, normalizeManagerDef(mDef));
            } else if (sDef) {
                defs.set(id, normalizeSystemDef(sDef));
            }
        }

        return defs;
    }

    /**
     * Get or build the definitions map (lazy initialization)
     */
    function getDefinitions() {
        if (!_definitions) {
            _definitions = buildDefinitions();
        }
        return _definitions;
    }

    // ═══════════════════════════════════════════════════════════════════
    // V2 STORAGE
    // ═══════════════════════════════════════════════════════════════════

    /**
     * Get the v2 storage data
     */
    function getV2Data() {
        try {
            const raw = localStorage.getItem(STORAGE_KEY_V2);
            if (raw) {
                const data = JSON.parse(raw);
                if (data && data.version === 2 && data.unlocked) {
                    return data;
                }
            }
        } catch (e) {
            console.warn('AchievementRegistry: Error reading v2 storage', e);
        }
        return null;
    }

    /**
     * Save v2 storage data
     */
    function saveV2Data(data) {
        localStorage.setItem(STORAGE_KEY_V2, JSON.stringify(data));
    }

    /**
     * Migrate/reconcile v1 storage into v2.
     * Runs on every init — merges any v1 entries missing from v2.
     * Content pages only write to v1 (AchievementRegistry isn't loaded there),
     * so v2 can fall behind. This reconciliation keeps them in sync.
     */
    function migrate() {
        const existing = getV2Data();
        const v2 = existing || { version: 2, unlocked: {}, migratedAt: Date.now() };

        let added = 0;
        try {
            const raw = JSON.parse(localStorage.getItem(STORAGE_KEY_OLD) || '[]');
            for (const entry of raw) {
                if (typeof entry === 'string') {
                    if (entry && !v2.unlocked[entry]) {
                        v2.unlocked[entry] = { unlockedAt: null, source: 'manager' };
                        added++;
                    }
                } else if (entry && entry.id) {
                    if (!v2.unlocked[entry.id]) {
                        v2.unlocked[entry.id] = {
                            unlockedAt: entry.unlockedAt || null,
                            source: 'system'
                        };
                        added++;
                    }
                }
            }
        } catch (e) {
            console.warn('AchievementRegistry: Error reconciling achievements', e);
        }

        if (!existing || added > 0) {
            saveV2Data(v2);
            if (added > 0) {
                console.log(`AchievementRegistry: Reconciled ${added} achievements from v1 into v2 (${Object.keys(v2.unlocked).length} total)`);
            }
        }
        return v2;
    }

    // ═══════════════════════════════════════════════════════════════════
    // PUBLIC API — DEFINITIONS
    // ═══════════════════════════════════════════════════════════════════

    /**
     * Get a single achievement definition by ID
     */
    function getDefinition(id) {
        return getDefinitions().get(id) || null;
    }

    /**
     * Get all achievement definitions as an array
     */
    function getAllDefinitions() {
        return Array.from(getDefinitions().values());
    }

    /**
     * Get all definitions in a specific category
     */
    function getByCategory(category) {
        return getAllDefinitions().filter(d => d.category === category);
    }

    /**
     * Get all definitions in a specific subcategory
     */
    function getBySubcategory(subcategory) {
        return getAllDefinitions().filter(d => d.subcategory === subcategory);
    }

    /**
     * Get list of all categories with counts
     */
    function getCategories() {
        if (!_categories) {
            const cats = {};
            for (const def of getDefinitions().values()) {
                const cat = def.category;
                if (!cats[cat]) {
                    cats[cat] = { id: cat, label: CATEGORY_LABELS[cat] || cat, count: 0 };
                }
                cats[cat].count++;
            }
            _categories = Object.values(cats).sort((a, b) => a.label.localeCompare(b.label));
        }
        return _categories;
    }

    /**
     * Total number of defined achievements (hand-crafted + auto-generated)
     */
    function count() {
        return getDefinitions().size;
    }

    // ═══════════════════════════════════════════════════════════════════
    // PUBLIC API — UNLOCK STATE (V2)
    // ═══════════════════════════════════════════════════════════════════

    /**
     * Check if an achievement is unlocked in v2 storage
     */
    function isUnlocked(id) {
        const v2 = getV2Data();
        if (!v2) return false;
        return id in v2.unlocked;
    }

    /**
     * Get all unlocked achievement IDs
     */
    function getUnlockedIds() {
        const v2 = getV2Data();
        if (!v2) return [];
        return Object.keys(v2.unlocked);
    }

    /**
     * Get all unlocked achievements with full definitions
     */
    function getUnlockedAchievements() {
        const ids = getUnlockedIds();
        const defs = getDefinitions();
        return ids.map(id => {
            const def = defs.get(id);
            const v2 = getV2Data();
            const unlockData = v2 ? v2.unlocked[id] : null;
            return def ? { ...def, unlockedAt: unlockData?.unlockedAt || null } : { id, unlockedAt: unlockData?.unlockedAt || null };
        });
    }

    /**
     * Unlock an achievement in v2 storage.
     * Also writes to old key for backward compatibility with pages not yet migrated.
     */
    function unlock(id) {
        // Ensure migration has happened
        let v2 = getV2Data();
        if (!v2) v2 = migrate();

        if (v2.unlocked[id]) return false; // Already unlocked

        // Store even if definition unknown — Manager/System validated the ID already.
        // Content pages may unlock achievements before Registry has all definitions.
        const def = getDefinition(id);
        if (!def) {
            console.warn('AchievementRegistry: No definition for', id, '— storing anyway');
        }

        v2.unlocked[id] = { unlockedAt: Date.now(), source: 'registry' };
        saveV2Data(v2);

        // Backward-compat: also write to old key as string ID
        try {
            const old = JSON.parse(localStorage.getItem(STORAGE_KEY_OLD) || '[]');
            const oldIds = old.map(e => typeof e === 'string' ? e : (e?.id || ''));
            if (!oldIds.includes(id)) {
                old.push(id);
                localStorage.setItem(STORAGE_KEY_OLD, JSON.stringify(old));
            }
        } catch (e) { /* old key write is best-effort */ }

        return true;
    }

    /**
     * Get unified stats
     */
    function getStats() {
        const defs = getDefinitions();
        const unlockedIds = getUnlockedIds();
        const validUnlocked = unlockedIds.filter(id => defs.has(id));

        let totalPoints = 0;
        let secretsFound = 0;
        let legendaryFound = 0;

        for (const id of validUnlocked) {
            const def = defs.get(id);
            if (def) {
                totalPoints += def.points;
                if (def.secret) secretsFound++;
                if (def.category === 'legendary' || def.style === 'legendary') legendaryFound++;
            }
        }

        return {
            total: defs.size,
            unlocked: validUnlocked.length,
            points: totalPoints,
            secretsFound,
            legendaryFound,
            percentage: defs.size > 0 ? Math.round((validUnlocked.length / defs.size) * 100) : 0
        };
    }

    /**
     * Get stats for a specific category
     */
    function getCategoryStats(category) {
        const catDefs = getByCategory(category);
        const unlockedIds = new Set(getUnlockedIds());
        const unlocked = catDefs.filter(d => unlockedIds.has(d.id));
        return {
            total: catDefs.length,
            unlocked: unlocked.length,
            percentage: catDefs.length > 0 ? Math.round((unlocked.length / catDefs.length) * 100) : 0
        };
    }

    /**
     * Force rebuild of the definitions cache (call after adding auto-generated)
     */
    function invalidateCache() {
        _definitions = null;
        _categories = null;
    }

    /**
     * Add auto-generated achievement definitions
     */
    function addDefinitions(defs) {
        const map = getDefinitions();
        for (const def of defs) {
            if (!map.has(def.id)) {
                map.set(def.id, def);
            }
        }
        _categories = null; // Invalidate category cache
    }

