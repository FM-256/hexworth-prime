/**
 * TrophyCabinet.js — the unified, PlayStation-style trophy cabinet.
 *
 * PHILOSOPHY (see the badge-merge analysis): this combines the VIEW, not the
 * plumbing. It READS from the existing systems and never migrates or re-awards:
 *   - Core achievements  → AchievementRegistry (already merges AchievementSystem
 *                          + AchievementManager into one normalized schema).
 *   - Sandbox badges     → ObservatoryBadges (shared defs) + the durable progress
 *                          doc for earned state.
 * No storage is merged, no earned data is moved, and server-issued badges keep
 * their integrity (we only read what AchievementRegistry/AchievementSystem already
 * expose). This is deliberately non-destructive.
 *
 * WHAT IT ADDS (the PlayStation feel):
 *   - TIERS: every badge is Bronze / Silver / Gold by points (the existing rarity
 *     bands collapsed to PlayStation's three), plus a synthetic PLATINUM per set,
 *     earned when every non-secret, non-pending badge in that set is complete.
 *   - SETS: badges grouped into collections (each core category + the Sandbox),
 *     each with a completion % and a Platinum slot.
 *   - PROFILE LEVEL: one points-weighted number aggregating every trophy.
 */
(function () {
    'use strict';

    // ── Tiers ────────────────────────────────────────────────────────────────
    // Bronze/Silver/Gold derive from points (the same bands the rarity system
    // already uses, collapsed to three). Platinum is NOT point-based — it is a
    // set-completion capstone, handled per set below.
    var TIER = { BRONZE: 'bronze', SILVER: 'silver', GOLD: 'gold', PLATINUM: 'platinum' };

    // PlayStation-style trophy weights, used to compute the profile level so a
    // Gold is worth meaningfully more than a Bronze and a Platinum crowns a set.
    var TIER_WEIGHT = { bronze: 15, silver: 30, gold: 90, platinum: 180 };

    // A badge's base tier from its points (legendary style always tops out Gold).
    function tierOf(points, style) {
        if (style === 'legendary' || style === 'cosmic') return TIER.GOLD;
        if (points >= 200) return TIER.GOLD;
        if (points >= 100) return TIER.SILVER;
        return TIER.BRONZE;
    }

    // ── Set naming ───────────────────────────────────────────────────────────
    // Turn a raw category key into a display name (Registry already maps most,
    // but we defend against raw snake_case leaking through).
    function humanizeSet(key) {
        if (!key) return 'General';
        return String(key)
            .replace(/[-_]+/g, ' ')
            .replace(/\b\w/g, function (c) { return c.toUpperCase(); });
    }

    // ── Sources (injectable for testing; default to the live globals) ─────────
    function coreSource() {
        if (typeof AchievementRegistry === 'undefined') return null;
        return AchievementRegistry;
    }
    function obsSource() {
        if (typeof ObservatoryBadges === 'undefined') return null;
        return ObservatoryBadges;
    }

    // ── Model builder ────────────────────────────────────────────────────────
    // Produces the full cabinet model: { profile, sets: [...] }. Pure w.r.t. its
    // sources — pass overrides in opts for tests, else it reads the live systems.
    function buildModel(opts) {
        opts = opts || {};
        var core = opts.core || coreSource();
        var obs = opts.obs || obsSource();

        // The 5 legacy sandbox badges are CORE achievements (same ids) surfaced in
        // the Sandbox set. Exclude their ids from the core sets so they are not
        // double-counted — the Sandbox set is their single home in the cabinet.
        var legacyIds = {};
        var obsDefs = (obs && obs.DEFS) || [];
        obsDefs.forEach(function (d) { if (d.legacy) legacyIds[d.id] = true; });

        var badges = [];
        var coreIds = {};                              // every id we placed in a core set

        // Core achievements → one badge each (minus the legacy dupes).
        if (core && core.getAllDefinitions) {
            var unlocked = {};
            (core.getUnlockedIds ? core.getUnlockedIds() : []).forEach(function (id) { unlocked[id] = true; });
            core.getAllDefinitions().forEach(function (def) {
                // The cabinet is a CURATED trophy room, not a progress ledger. Exclude
                // AchievementRegistry's ~6,600 auto-generated per-content completion
                // badges (auto_lab/auto_quiz/house-presentation/milestone/streak/xp):
                // they have no badge art (generic icon), dwarf the curated set 20:1, and
                // completion tracking already lives in the dashboard/course views. Only
                // the ~336 hand-authored trophies (+ the Sandbox set) belong here.
                if (def.autoGenerated) return;
                if (legacyIds[def.id]) return;             // lives in the Sandbox set instead
                coreIds[def.id] = true;
                var pts = def.points || 0;
                badges.push({
                    id: def.id,
                    name: def.name || def.id,
                    description: def.description || '',
                    art: def.id,                            // core art is keyed by id
                    points: pts,
                    tier: tierOf(pts, def.style),
                    legendary: (def.style === 'legendary' || def.style === 'cosmic' || pts >= 500),
                    setId: def.category || 'general',
                    source: 'core',
                    secret: !!def.secret,
                    pending: false,
                    earned: !!unlocked[def.id]
                });
            });
        }

        // Sandbox badges (all 25 obs defs, including legacy + pending) → one set.
        // Dedup is by the `legacy` flag, but guard structurally too: if a NON-legacy
        // obs id ever collides with a core id, it would double-count silently. Skip
        // it and warn rather than trusting the flag convention alone (Nancy #4).
        var prog = (obs && obs.readProgress) ? obs.readProgress() : {};
        obsDefs.forEach(function (def) {
            if (!def.legacy && coreIds[def.id]) {
                if (typeof console !== 'undefined') console.warn('TrophyCabinet: obs id "' + def.id + '" collides with a core achievement id — skipping to avoid double-count');
                return;
            }
            var pts = def.pts || 0;
            badges.push({
                id: def.id,
                name: def.name || def.id,
                description: def.desc || '',
                art: def.art || def.id,                     // obs art is keyed by def.art stem
                points: pts,
                tier: tierOf(pts, def.style),
                legendary: (def.style === 'legendary' || pts >= 500),
                setId: 'sandbox',
                source: 'sandbox',
                secret: false,
                pending: !!def.pending,
                earned: def.pending ? false : (obs && obs.earned ? obs.earned(def, prog) : false)
            });
        });

        // Group into sets.
        var setMap = {};
        badges.forEach(function (b) {
            if (!setMap[b.setId]) setMap[b.setId] = { id: b.setId, name: b.setId === 'sandbox' ? 'Linux Sandbox' : humanizeSet(b.setId), badges: [] };
            setMap[b.setId].badges.push(b);
        });

        var sets = Object.keys(setMap).map(function (id) {
            var s = setMap[id];
            // ONE population drives the count, the percentage, and the Platinum gate:
            // every badge that is EARNABLE right now = all non-pending badges. Secrets
            // ARE earnable (just masked until earned), so they count and are required
            // for Platinum, PlayStation-style. Pending badges (server check not wired)
            // are genuinely not earnable yet — they are shown as "coming soon" but do
            // not count, and their mere presence keeps the set's Platinum locked (the
            // set is not completable until every trophy is actually available).
            var earnable = s.badges.filter(function (b) { return !b.pending; });
            var earnedCount = earnable.filter(function (b) { return b.earned; }).length;
            var pendingCount = s.badges.length - earnable.length;
            var platinum = earnable.length > 0 && earnedCount === earnable.length && pendingCount === 0;
            return {
                id: s.id,
                name: s.name,
                badges: s.badges,
                total: earnable.length,             // display denominator = what's earnable
                earned: earnedCount,
                eligibleTotal: earnable.length,     // kept for callers; same population now
                pendingCount: pendingCount,
                platinum: platinum,
                // Collapsed by default so the page is a navigable index, not a 12k-px
                // wall; only the flagship Sandbox set opens on load. Users expand the
                // rest via the header or the summary strip.
                open: s.id === 'sandbox',
                pctComplete: earnable.length ? Math.round((earnedCount / earnable.length) * 100) : 0
            };
        }).sort(function (a, b) {
            // Sandbox first (it is the flagship set), then most-complete, then name.
            if (a.id === 'sandbox') return -1;
            if (b.id === 'sandbox') return 1;
            if (b.pctComplete !== a.pctComplete) return b.pctComplete - a.pctComplete;
            return a.name.localeCompare(b.name);
        });

        // Profile roll-up.
        var tierCounts = { bronze: 0, silver: 0, gold: 0, platinum: 0 };
        var levelPoints = 0;
        badges.forEach(function (b) {
            if (b.earned) { tierCounts[b.tier]++; levelPoints += TIER_WEIGHT[b.tier] || 0; }
        });
        sets.forEach(function (s) { if (s.platinum) { tierCounts.platinum++; levelPoints += TIER_WEIGHT.platinum; } });

        var totalEarned = badges.filter(function (b) { return b.earned; }).length;
        var totalBadges = badges.filter(function (b) { return !b.pending; }).length;   // don't count un-earnable in the denominator

        // Spotlight for the banner's right side (otherwise dead space): the rarest
        // trophy already earned, and the set closest to a Platinum — a "you're this
        // close" nudge. Both may be null (nothing earned / no set in progress).
        var rarest = null;
        badges.forEach(function (b) { if (b.earned && (!rarest || b.points > rarest.points)) rarest = b; });
        var nextPlat = null;
        sets.forEach(function (s) {
            if (!s.platinum && s.earned > 0 && (!nextPlat || s.pctComplete > nextPlat.pctComplete)) nextPlat = s;
        });
        var spotlight = {
            rarest: rarest ? { name: rarest.name, art: rarest.art, tier: rarest.tier, points: rarest.points } : null,
            nextPlat: nextPlat ? { name: nextPlat.name, pct: nextPlat.pctComplete, remaining: nextPlat.total - nextPlat.earned } : null
        };

        return {
            profile: {
                level: levelFromPoints(levelPoints),
                levelPoints: levelPoints,
                tierCounts: tierCounts,
                totalEarned: totalEarned,
                totalBadges: totalBadges,
                pctComplete: totalBadges ? Math.round((totalEarned / totalBadges) * 100) : 0,
                spotlight: spotlight
            },
            sets: sets
        };
    }

    // Points → level. A gentle escalating curve (each level costs a bit more),
    // so early levels come quick and later ones feel earned — the PlayStation
    // trophy-level shape. Level 1 at 0 points.
    function levelFromPoints(pts) {
        var lvl = 1, need = 60, acc = 0;
        while (acc + need <= pts) { acc += need; lvl++; need = Math.round(need * 1.15); }
        return lvl;
    }

    // ── View ─────────────────────────────────────────────────────────────────
    // render(model) → HTML string for the whole cabinet. Pure; caller injects it.
    // Text from our own def files is trusted, but we escape anyway (cheap, and it
    // future-proofs against a def that ever carries a stray angle bracket).
    var BADGE_ART = '/assets/images/badges/';
    var ART_FALLBACK = BADGE_ART + 'first_visit.webp';   // known-present; used on 404

    // Escape HTML special chars so def text is safe in both attribute and text positions.
    function esc(s) {
        return String(s == null ? '' : s)
            .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;');
    }

    function badgeHtml(b) {
        var earned = !!b.earned;
        var hidden = b.secret && !earned;            // secret + unearned = mystery tile
        var cls = ['tc-badge', 'tc-badge--' + b.tier];
        if (b.legendary) cls.push('tc-badge--legendary');
        cls.push(earned ? 'is-earned' : 'is-locked');
        if (hidden) cls.push('is-secret');
        if (b.pending) cls.push('is-pending');

        var name = hidden ? 'Hidden Trophy' : esc(b.name);
        // Art wrapper — the tier RING lives here (earned only); no sticker pill on the
        // artwork anymore. Tier is named in the meta line below instead, so it reads
        // on every tile (earned or locked) without occluding the image.
        var art = '<div class="tc-badge__art">' +
            '<img data-fallback="1" src="' + esc(BADGE_ART + b.art + '.webp') + '" alt="">' +
            '</div>';
        // Meta line carries the tier word + value (or the state for hidden/pending),
        // and reads on locked tiles too so a learner sees what each trophy is worth.
        var tierWord = '<span class="tc-badge__tier">' + esc(b.tier.toUpperCase()) + '</span>';
        var meta = hidden
            ? '<div class="tc-badge__meta">Classified</div>'
            : (b.pending && !earned
                ? '<div class="tc-badge__meta">' + tierWord + ' &middot; Coming soon</div>'
                : '<div class="tc-badge__meta">' + tierWord + ' &middot; ' + (b.points || 0) + ' pts</div>');
        return '<div class="' + cls.join(' ') + '" data-badge="' + esc(b.id) + '">' +
            art + '<div class="tc-badge__name">' + name + '</div>' + meta + '</div>';
    }

    // Returns the HTML for one COLLAPSIBLE trophy set. The header is a button that
    // toggles the body (bar + grid); it always shows the name, count, completion bar,
    // and Platinum medallion so a collapsed set is still informative at a glance.
    function setHtml(s) {
        var platCls = 'tc-plat' + (s.platinum ? ' tc-plat--earned' : '');
        // The Platinum tooltip states WHY it is locked: still-to-earn vs. not-yet-available.
        var platTitle = s.platinum
            ? 'Platinum earned — every trophy in this set is complete'
            : (s.pendingCount > 0
                ? 'Platinum locked — unlocks when the remaining trophies go live'
                : 'Platinum locked — earn every trophy in this set');
        // "N coming soon" reconciles the count (earnable) with the tiles shown (which
        // include the pending ones), so the numbers never read as missing badges.
        var soon = s.pendingCount > 0
            ? ' <span class="tc-set__soon">&middot; ' + s.pendingCount + ' coming soon</span>' : '';
        var openCls = s.open ? ' is-open' : '';
        return '<section class="tc-set' + openCls + '" data-set="' + esc(s.id) + '" id="tc-set-' + esc(s.id) + '">' +
            '<button type="button" class="tc-set__head" aria-expanded="' + (s.open ? 'true' : 'false') + '">' +
                '<span class="tc-set__chevron" aria-hidden="true"></span>' +
                '<span class="tc-set__name">' + esc(s.name) + '</span>' +
                '<span class="tc-set__meta">' + s.earned + ' / ' + s.total + ' &middot; ' + s.pctComplete + '%' + soon + '</span>' +
                '<span class="tc-set__minibar"><i style="width:' + s.pctComplete + '%"></i></span>' +
                '<span class="' + platCls + '" title="' + esc(platTitle) + '"></span>' +
            '</button>' +
            '<div class="tc-set__body">' +
                '<div class="tc-grid">' + s.badges.map(badgeHtml).join('') + '</div>' +
            '</div>' +
        '</section>';
    }

    // The summary strip — a horizontal, scrollable index of every set. Each chip jumps
    // to (and expands) its set. This is the "table of contents" over the collapsed page.
    function indexHtml(sets) {
        var chips = sets.map(function (s) {
            var dot = s.platinum ? '<span class="tc-chip__plat" title="Platinum earned"></span>' : '';
            return '<button type="button" class="tc-chip" data-target="tc-set-' + esc(s.id) + '">' +
                dot + '<span class="tc-chip__name">' + esc(s.name) + '</span>' +
                '<span class="tc-chip__count">' + s.earned + '/' + s.total + '</span>' +
                '</button>';
        }).join('');
        return '<nav class="tc-index" aria-label="Trophy sets">' + chips + '</nav>';
    }

    // One tier tally for the profile banner: a colored medal + count + label.
    function tierCountHtml(tier, n, label) {
        return '<span class="tc-tiercount"><span class="tc-medal tc-medal--' + tier + '"></span>' +
            '<b>' + n + '</b> ' + label + '</span>';
    }

    // The banner's right side: a spotlight on the rarest trophy earned and the set
    // closest to a Platinum. Fills what was dead space; degrades to nothing if the
    // player has earned nothing yet.
    function spotlightHtml(sp) {
        if (!sp || (!sp.rarest && !sp.nextPlat)) return '';
        var parts = '';
        if (sp.rarest) {
            parts += '<div class="tc-spot__card">' +
                '<div class="tc-spot__label">Rarest trophy</div>' +
                '<div class="tc-spot__row">' +
                    '<img class="tc-spot__art" data-fallback="1" src="' + esc(BADGE_ART + sp.rarest.art + '.webp') + '" alt="">' +
                    '<div><div class="tc-spot__name">' + esc(sp.rarest.name) + '</div>' +
                    '<div class="tc-spot__sub">' + esc(sp.rarest.tier.toUpperCase()) + ' &middot; ' + sp.rarest.points + ' pts</div></div>' +
                '</div></div>';
        }
        if (sp.nextPlat) {
            parts += '<div class="tc-spot__card">' +
                '<div class="tc-spot__label">Closest Platinum</div>' +
                '<div class="tc-spot__name">' + esc(sp.nextPlat.name) + '</div>' +
                '<div class="tc-spot__sub">' + sp.nextPlat.pct + '% &middot; ' + sp.nextPlat.remaining + ' to go</div>' +
                '</div>';
        }
        return '<div class="tc-spot">' + parts + '</div>';
    }

    // The top banner: Trophy Level chip, earned/total summary, per-tier tallies,
    // the overall completion bar, and the spotlight on the right.
    function profileHtml(p) {
        var t = p.tierCounts;
        return '<header class="tc-profile">' +
            '<div class="tc-level"><div class="tc-level__num">' + p.level + '</div>' +
                '<div class="tc-level__label">Trophy Level</div></div>' +
            '<div class="tc-profile__main">' +
                '<div class="tc-profile__title">Trophy Cabinet</div>' +
                '<div class="tc-profile__sub"><b>' + p.totalEarned + '</b> of <b>' + p.totalBadges +
                    '</b> trophies earned &middot; ' + p.pctComplete + '% complete</div>' +
                '<div class="tc-tiercounts">' +
                    tierCountHtml('platinum', t.platinum, 'Platinum') +
                    tierCountHtml('gold', t.gold, 'Gold') +
                    tierCountHtml('silver', t.silver, 'Silver') +
                    tierCountHtml('bronze', t.bronze, 'Bronze') +
                '</div>' +
                '<div class="tc-progress"><i style="width:' + p.pctComplete + '%"></i></div>' +
            '</div>' +
            spotlightHtml(p.spotlight) +
        '</header>';
    }

    // render(model) → HTML string. NOTE: 27+ core badge ids have no art file, so the
    // <img>s carry data-fallback and rely on wireArtFallbacks() to swap 404s for a
    // known-present image. If you inject this HTML yourself instead of using mount(),
    // you MUST call TrophyCabinet.wireArtFallbacks(container) afterward or those tiles
    // show broken images. mount() does both for you.
    function render(model) {
        model = model || buildModel();
        return '<div class="tc">' + profileHtml(model.profile) +
            indexHtml(model.sets) +
            model.sets.map(setHtml).join('') + '</div>';
    }

    // Swap any 404'd badge art for a known-present fallback. CSP-clean (JS listeners,
    // not inline onerror). The one-shot removeEventListener guards against a loop if
    // the fallback image itself 404s.
    function wireArtFallbacks(el) {
        if (!el) return;
        var imgs = el.querySelectorAll('img[data-fallback]');
        Array.prototype.forEach.call(imgs, function (img) {
            img.addEventListener('error', function onErr() {
                img.removeEventListener('error', onErr);
                img.src = ART_FALLBACK;
            });
        });
    }

    // Wire the collapsible set headers and the summary-strip jump chips. Uses one
    // delegated click listener so it survives any number of sets and needs no cleanup.
    function wireInteractions(el) {
        if (!el || !el.addEventListener) return;
        el.addEventListener('click', function (e) {
            var head = e.target.closest ? e.target.closest('.tc-set__head') : null;
            if (head) {
                var sec = head.parentNode;
                var open = sec.classList.toggle('is-open');
                head.setAttribute('aria-expanded', open ? 'true' : 'false');
                return;
            }
            var chip = e.target.closest ? e.target.closest('.tc-chip') : null;
            if (chip) {
                var target = el.querySelector('#' + (chip.getAttribute('data-target') || '').replace(/"/g, ''));
                if (target) {
                    target.classList.add('is-open');
                    var h = target.querySelector('.tc-set__head');
                    if (h) h.setAttribute('aria-expanded', 'true');
                    target.scrollIntoView({ behavior: 'smooth', block: 'start' });
                }
            }
        });
    }

    // mount(el, opts) — inject the cabinet into a container AND wire art fallbacks +
    // collapse/jump interactions. Returns the model. The safe, complete entry point.
    function mount(el, opts) {
        if (!el) return null;
        var model = (opts && opts.model) || buildModel(opts);
        el.innerHTML = render(model);
        wireArtFallbacks(el);
        wireInteractions(el);
        return model;
    }

    window.TrophyCabinet = {
        TIER: TIER,
        TIER_WEIGHT: TIER_WEIGHT,
        tierOf: tierOf,
        levelFromPoints: levelFromPoints,
        buildModel: buildModel,
        render: render,
        wireArtFallbacks: wireArtFallbacks,
        mount: mount
    };
})();
